"""
Self-host fonts and animation libraries (no requests to Google / CDNs from the visitor's browser -> GDPR).

  python tools/fetch_vendor.py

Writes:
  assets/fonts/<family>-<subset>.woff2   Jost (wght 300..600) + Instrument Sans (wght 400..600), latin + latin-ext
  assets/fonts/OFL-<family>.txt          SIL Open Font License (must ship with the font files)
  css/fonts.css                          @font-face rules (linked in index.html before style.css)
  assets/vendor/lenis.min.js, gsap.min.js, ScrollTrigger.min.js   same versions the site used from the CDN

Load order in index.html stays: lenis -> gsap -> ScrollTrigger -> js/app.js (end of <body>).
Re-running overwrites the files; bump the versions below to update.
"""
import os, re, sys, urllib.request

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36"
LENIS, GSAP = "1.1.13", "3.12.5"
FONTS = [("Jost", "jost", "wght@300..600", "300 600", "ofl/jost/OFL.txt"),
         ("Instrument Sans", "instrument-sans", "wght@400..600", "400 600", "ofl/instrumentsans/OFL.txt")]
KEEP = ("latin", "latin-ext")


def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    data = urllib.request.urlopen(req, timeout=60).read()
    return data if binary else data.decode("utf-8")


def fonts():
    out = os.path.join(ROOT, "assets", "fonts"); os.makedirs(out, exist_ok=True)
    css = ["/* generated by tools/fetch_vendor.py - self-hosted, no Google Fonts request */"]
    for family, slug, axis, weight, ofl in FONTS:
        src = get(f"https://fonts.googleapis.com/css2?family={family.replace(' ', '+')}:{axis}&display=swap")
        for subset, block in re.findall(r"/\* ([a-z-]+) \*/\s*@font-face\s*{(.*?)}", src, re.S):
            if subset not in KEEP:
                continue
            url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
            rng = re.search(r"unicode-range:\s*([^;]+);", block).group(1)
            name = f"{slug}-{subset}.woff2"
            data = get(url, binary=True); open(os.path.join(out, name), "wb").write(data)
            css.append(f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};font-display:swap;'
                       f'src:url("../assets/fonts/{name}") format("woff2");unicode-range:{rng}}}')
            print(f"[font] {name}  {len(data) // 1024} KB")
        lic = get(f"https://raw.githubusercontent.com/google/fonts/main/{ofl}")
        open(os.path.join(out, f"OFL-{slug}.txt"), "w", encoding="utf-8").write(lic)
    open(os.path.join(ROOT, "css", "fonts.css"), "w", encoding="utf-8").write("\n".join(css) + "\n")
    print("[ok] css/fonts.css")


def libs():
    out = os.path.join(ROOT, "assets", "vendor"); os.makedirs(out, exist_ok=True)
    for name, url in (("lenis.min.js", f"https://unpkg.com/lenis@{LENIS}/dist/lenis.min.js"),
                      ("gsap.min.js", f"https://cdnjs.cloudflare.com/ajax/libs/gsap/{GSAP}/gsap.min.js"),
                      ("ScrollTrigger.min.js", f"https://cdnjs.cloudflare.com/ajax/libs/gsap/{GSAP}/ScrollTrigger.min.js")):
        data = get(url, binary=True); open(os.path.join(out, name), "wb").write(data)
        print(f"[lib] {name}  {len(data) // 1024} KB")


if __name__ == "__main__":
    fonts(); libs()
